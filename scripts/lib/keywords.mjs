// 품목 자리에 오면 안 되는 꼬리말. 폴백에서만 쓴다.
const TAIL_NOISE = /^(.*향|.*맛|본품|리필|세트|정품|구성|추가|증정|옵션|선택|무료배송|특가|신상|[0-9].*)$/;

const norm = (s) => s.toLowerCase().replace(/[\s\-_]/g, '');

const UNIT = /^[0-9][0-9.,xX*]*\s*(ml|l|g|kg|mg|개입|개|입|매|포|족|켤레|겹|ply|구|인치|cm|mm|종|팩|년|월|단|호|w|a|v|gb|tb|인용|세트|p)?$/i;
const MODEL = /^[A-Za-z0-9][A-Za-z0-9.-]*$/;

function tokens(title) {
  return String(title || '')
    .replace(/[[\](){}/·,+]/g, ' ')
    .split(/\s+/)
    .map((w) => w.replace(/^-+|-+$/g, ''))
    .filter((w) => w.length >= 2 && !UNIT.test(w) && !MODEL.test(w));
}

// 품목 하나를 찾는다. 사전 우선, 없으면 꼬리를 털어낸 마지막 명사.
function findItem(title) {
  const hay = norm(title);
  let best = '';
  for (const it of ITEMS) {
    if (hay.includes(norm(it)) && it.length > best.length) best = it;
  }
  if (best) return best;

  const ws = tokens(title);
  for (let i = ws.length - 1; i >= 1; i -= 1) {
    if (!TAIL_NOISE.test(ws[i])) return ws[i];
  }
  return '';
}

/**
 * 상품 하나의 태그를 뽑는다. 품목 → 특징 → 대상 순으로 최대 4개.
 * 품목을 못 찾으면 빈 배열(태그를 달지 않는다).
 */
export function extractTags(product, max = 4) {
  const title = product?.title || '';
  if (!title) return [];

  const item = findItem(title);
  if (!item) return [];

  const tags = [item];
  const hay = norm(title);
  // '베이비파우더향'은 향 이름이지 유아용품이 아니다. 대상을 볼 때는 향·맛을 뺀다.
  const hayTarget = norm(
    String(title).split(/\s+/).filter((w) => !/(향|맛)$/.test(w)).join(' ')
  );

  for (const m of MODIFIERS) {
    if (tags.length >= max) break;
    if (hay.includes(norm(m)) && !tags.includes(m)) tags.push(m);
  }
  for (const [word, label] of Object.entries(TARGETS)) {
    if (tags.length >= max) break;
    if (hayTarget.includes(norm(word)) && !tags.includes(label)) tags.push(label);
  }
  return tags;
}

/** 품목만 필요할 때(제목·설명 문구에 쓴다). */
export function itemOf(product) {
  return findItem(product?.title || '');
}
